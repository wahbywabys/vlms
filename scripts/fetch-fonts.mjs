#!/usr/bin/env node
/**
 * Self-host the app's Google Fonts so a training centre with no internet still
 * gets the right type (and pages never wait on fonts.googleapis.com).
 * Writes app/public/fonts/*.woff2 and app/src/app/fonts.css. Run once after
 * changing the font list, and commit the output:  node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FAMILIES = 'family=Barlow+Condensed:wght@500;600;700&family=Barlow:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500'
  + '&family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&family=Noto+Kufi+Arabic:wght@500;600;700&display=swap';
const KEEP = new Set(['latin', 'latin-ext', 'arabic']);   // English and Arabic UI
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const css = await (await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}`, { headers: { 'user-agent': UA } })).text();
const outDir = join(root, 'app/public/fonts');
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face\s*{[^}]+})/g)].filter((m) => KEEP.has(m[1]));
let out = '/* Generated by scripts/fetch-fonts.mjs: self-hosted Google Fonts (latin, latin-ext, arabic). */\n';
for (const [, subset, block] of blocks) {
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  const family = block.match(/font-family: '([^']+)'/)[1].toLowerCase().replace(/\s+/g, '-');
  const weight = block.match(/font-weight: (\d+)/)[1];
  const name = `${family}-${weight}-${subset}-${createHash('sha1').update(buf).digest('hex').slice(0, 8)}.woff2`;
  await writeFile(join(outDir, name), buf);
  out += `/* ${subset} */\n${block.replace(url, `/fonts/${name}`)}\n`;
}
await writeFile(join(root, 'app/src/app/fonts.css'), out);
console.log(`${blocks.length} font files written to app/public/fonts`);
